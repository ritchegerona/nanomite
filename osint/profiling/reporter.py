"""Report generation for OSINT profiles."""

from __future__ import annotations
import json
from pathlib import Path
from typing import Literal

from .config import Profile


def generate_report(
    profile: Profile,
    output_path: str | Path,
    format: Literal["markdown", "json"] = "markdown",
) -> None:
    """Generate a report for a profile."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    if format == "json":
        _generate_json(profile, path)
    else:
        _generate_markdown(profile, path)


def _generate_json(profile: Profile, path: Path) -> None:
    """Generate JSON report."""
    data = profile.to_dict()
    path.write_text(json.dumps(data, indent=2))


def _generate_markdown(profile: Profile, path: Path) -> None:
    """Generate Markdown report."""
    lines = [
        f"# OSINT Profile: {profile.target.alias}",
        f"**Generated:** {profile.generated_at}",
        f"**Confidence:** {profile.aggregate_confidence:.2f} ({profile.tier.value.upper()})",
        "",
        "## Target Identifiers",
    ]
    
    t = profile.target
    if t.all_aliases():
        lines.append(f"- **Aliases:** {', '.join(t.all_aliases())}")
    if t.telegram_usernames:
        lines.append(f"- **Telegram:** {', '.join(t.telegram_usernames)}")
    if t.facebook_ids:
        lines.append(f"- **Facebook IDs:** {', '.join(t.facebook_ids)}")
    if t.instagram_usernames:
        lines.append(f"- **Instagram:** {', '.join(t.instagram_usernames)}")
    if t.emails:
        lines.append(f"- **Emails:** {', '.join(t.emails)}")
    if t.domains:
        lines.append(f"- **Domains:** {', '.join(t.domains)}")
    
    lines.append("")
    lines.append("## Real Name Candidates")
    
    if profile.real_name_candidates:
        for i, name in enumerate(profile.real_name_candidates, 1):
            lines.append(f"{i}. {name}")
    else:
        lines.append("*None found*")
    
    lines.append("")
    lines.append("## Location Profile")
    
    loc = profile.location_profile
    if loc:
        for key, value in loc.items():
            lines.append(f"- **{key.replace('_', ' ').title()}:** {value}")
    else:
        lines.append("*No location data*")
    
    lines.append("")
    lines.append("## Evidence Chain")
    
    if profile.evidence:
        # Group by source
        by_source = {}
        for ev in profile.evidence:
            by_source.setdefault(ev.source, []).append(ev)
        
        for source, ev_list in by_source.items():
            lines.append(f"### {source.upper()} ({len(ev_list)} items)")
            lines.append("")
            for ev in ev_list:
                ws = ev.weighted_score()
                lines.append(
                    f"- **{ev.data_type}** (conf: {ev.confidence:.2f}, wt: {ev.weight:.2f}, ws: {ws:.4f})"
                )
                lines.append(f"  - Value: `{ev.raw_value[:200]}{'...' if len(ev.raw_value) > 200 else ''}`")
                if ev.metadata:
                    meta_str = ", ".join(f"{k}={v}" for k, v in ev.metadata.items())
                    lines.append(f"  - Meta: {meta_str}")
            lines.append("")
    else:
        lines.append("*No evidence collected*")
    
    lines.append("")
    lines.append("---")
    lines.append(f"*Report generated by OSINT Profiling Framework v1.0.0*")
    
    path.write_text('\n'.join(lines))