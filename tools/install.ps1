# nanomite-tools-install.ps1
#
# Install every tool under tools/custom/<category>/ so it is callable from
# ANY directory, on ANY computer (Windows PowerShell).
#
# Creates wrapper .ps1 and .bat shims in ~/AppData/Local/nanomite-tools/bin
# (or %PROGRAMFILES%\nanomite-tools\bin when run as Admin) that export
# NANOMITE_TOOLS_HOME and exec the real Python script.
#
# Usage (PowerShell, run from the nanomite/tools directory):
#   Set-ExecutionPolicy -ExecutionPolicy RemoteSigned -Scope CurrentUser
#   .\install.ps1
#
# After install, add the bin dir to your PATH:
#   $env:PATH = "<install-dir>\bin;$env:PATH"
#   # persist:
#   [Environment]::SetEnvironmentVariable("PATH", "<install-dir>\bin;$env:PATH", [EnvironmentVariableTarget]::User)
#
# Then run from anywhere:
#   whois_rdap example.com --json
#   spiderfoot -t example.com -m sfp_whois
#
# Authorized use only: run against assets you own or have explicit written
# permission to assess. Do not use to identify or dox individuals.

$ErrorActionPreference = 'Stop'

# --- locate python executable (python3 preferred, then python, then py launcher) ---
function Find-Python {
    foreach ($candidate in @('python3', 'python', 'py')) {
        $path = Get-Command $candidate -ErrorAction SilentlyContinue
        if ($path) { return $candidate }
    }
    return $null
}

$pythonCmd = Find-Python
if (-not $pythonCmd) {
    Write-Error "[!] No Python found on PATH. Install Python from https://www.python.org/ and re-run."
    exit 1
}

$PSScriptRoot = Resolve-Path $PSScriptRoot
$TOOLS_DIR = $PSScriptRoot
$CUSTOM_DIR = Join-Path $TOOLS_DIR "custom"

if (-not (Test-Path $CUSTOM_DIR)) {
    Write-Error "[!] $CUSTOM_DIR not found. Run this from the nanomite/tools directory."
    exit 1
}

# Pick install location
$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if ($isAdmin) {
    $TARGET_DIR = "C:\Program Files\nanomite-tools\bin"
} else {
    $LOCALAPPDATA = [Environment]::GetFolderPath("LocalApplicationData")
    $TARGET_DIR = Join-Path $LOCALAPPDATA "nanomite-tools" "bin"
}

New-Item -ItemType Directory -Path $TARGET_DIR -Force | Out-Null

# NANOMITE_TOOLS_HOME is set inside each wrapper so tools always resolve siblings
$env:NANOMITE_TOOLS_HOME = $TOOLS_DIR

$count = 0
$tools = Get-ChildItem -Path $CUSTOM_DIR -Recurse -Filter "*.py" -File
foreach ($tool in $tools) {
    $name = [System.IO.Path]::GetFileNameWithoutExtension($tool.FullName)
    $ps1Link = Join-Path $TARGET_DIR "$name.ps1"
    $batLink = Join-Path $TARGET_DIR "$name.bat"

    # --- PowerShell wrapper ---
    # Use format operator -f so $env: and $args stay literal in the generated file.
    $ps1Wrapper = @"
# Auto-generated by nanomite/tools/install.ps1
`$env:NANOMITE_TOOLS_HOME = '{0}'
{1} '{2}' `$args
"@ -f $TOOLS_DIR, $pythonCmd, $tool.FullName
    Set-Content -Path $ps1Link -Value $ps1Wrapper -Encoding UTF8

    # --- Batch wrapper (cmd.exe compatibility) ---
    # set "VAR=value" is the safe pattern for paths with spaces.
    $batWrapper = "@echo off`nset ""NANOMITE_TOOLS_HOME={0}""`n{1} ""{2}"" %*`n" -f $TOOLS_DIR, $pythonCmd, $tool.FullName
    Set-Content -Path $batLink -Value $batWrapper -Encoding ASCII

    $count++
}

Write-Host "`n[+] Installed $count tools to $TARGET_DIR"
Write-Host "[+] Python command: $pythonCmd"
Write-Host "[+] NANOMITE_TOOLS_HOME=$TOOLS_DIR"
Write-Host "[+] Default data/output dirs: %LOCALAPPDATA%\nanomite-tools\<tool>\"
Write-Host ""
Write-Host "Add $TARGET_DIR to your PATH, then run from anywhere:"
Write-Host "  whois_rdap example.com --json"
Write-Host "  spiderfoot -t example.com -m sfp_whois"
Write-Host ""
Write-Host "To persist PATH, run:"
Write-Host "  [Environment]::SetEnvironmentVariable(""PATH"", ""$TARGET_DIR;$env:PATH"", [EnvironmentVariableTarget]::User)"
