#!/usr/bin/env bash
# nanomite-tools-install.sh
#
# Install every tool under tools/custom/<category>/ so it is callable from
# ANY directory, on ANY Linux/macOS computer.
#
# Symlinks each tool into ~/.local/bin (or /usr/local/bin when root) with a
# wrapper that exports NANOMITE_TOOLS_HOME=<absolute tools dir> and execs
# the real script. Default data/output dirs resolve under XDG_DATA_HOME
# (~/.local/share/nanomite-tools) instead of the caller's cwd.
#
# Usage:
#   cd /path/to/nanomite/tools && ./install.sh
#   ./install.sh --portable /opt/nanomite-tools   # install to a custom dir
#
# After install, ensure the bin dir is on your PATH, then run from anywhere:
#   whois_rdap example.com --json
#   spiderfoot -t example.com -m sfp_whois
#
# Authorized use only: run against assets you own or have explicit written
# permission to assess. Do not use to identify or dox individuals.

set -euo pipefail

PORTABLE_MODE=false
PORTABLE_DIR=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --portable)
            PORTABLE_MODE=true
            shift
            PORTABLE_DIR="${1:-}"
            shift
            ;;
        --help|-h)
            echo "Usage: $0 [--portable <dir>]"
            echo "  --portable <dir>   Install shims to <dir>/bin instead of ~/.local/bin"
            exit 0
            ;;
        *)
            echo "[!] Unknown argument: $1" >&2
            exit 1
            ;;
    esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS_DIR="${SCRIPT_DIR}"               # .../tools (this script lives there)
CUSTOM_DIR="${TOOLS_DIR}/custom"

if [[ ! -d "${CUSTOM_DIR}" ]]; then
    echo "[!] ${CUSTOM_DIR} not found. Run this from the nanomite/tools directory." >&2
    exit 1
fi

if [[ "${PORTABLE_MODE}" == true ]]; then
    if [[ -z "${PORTABLE_DIR}" ]]; then
        echo "[!] --portable requires a directory argument." >&2
        exit 1
    fi
    mkdir -p "${PORTABLE_DIR}"
    TARGET_DIR="$(cd "${PORTABLE_DIR}" && pwd)/bin"
    mkdir -p "${TARGET_DIR}"
else
    if [[ "$(id -u)" -eq 0 ]]; then
        TARGET_DIR="/usr/local/bin"
    else
        TARGET_DIR="${HOME}/.local/bin"
    fi
fi

mkdir -p "${TARGET_DIR}"

export NANOMITE_TOOLS_HOME="${TOOLS_DIR}"

count=0
while IFS= read -r -d '' tool; do
    name="$(basename "${tool}" .py)"
    link="${TARGET_DIR}/${name}"

    cat > "${link}" <<WRAPPER
#!/usr/bin/env bash
# Auto-generated by nanomite/tools/install.sh
export NANOMITE_TOOLS_HOME="${TOOLS_DIR}"
exec python3 "${tool}" "\$@"
WRAPPER
    chmod +x "${link}"
    count=$((count + 1))
done < <(find "${CUSTOM_DIR}" -type f -name '*.py' -print0)

echo "[+] Installed ${count} tools to ${TARGET_DIR}"
echo "[+] NANOMITE_TOOLS_HOME=${TOOLS_DIR}"
echo "[+] Default data/output dirs: ~/.local/share/nanomite-tools/<tool>/"
echo "[+] Add ${TARGET_DIR} to your PATH if it is not already:"
echo "    export PATH=\"${TARGET_DIR}:\$PATH\""
echo ""
echo "[+] To make it persistent, add the export line to ~/.bashrc, ~/.zshrc, or ~/.profile"